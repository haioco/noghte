def fa(n):
    """Persian digits with thousands separators."""
    return f"{n:,}".translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


def lead_bullet(doc, lead, text, size=11):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.right_indent = Cm(0.55)
    pf.first_line_indent = Cm(-0.40)
    pf.space_before = Pt(0)
    pf.space_after = Pt(3)
    pf.line_spacing = 1.4
    r = p.add_run("•  ")
    style_run(r, size=size, bold=True, color=BLUE)
    r1 = p.add_run(lead + ": ")
    style_run(r1, size=size, bold=True, color=NAVY)
    r2 = p.add_run(text)
    style_run(r2, size=size)
    rtl_paragraph(p)
    return p


def ltr_center_line(doc, text, size=9.5, color="808080"):
    """Centred Latin line; no bidi/rtl so the English title stays readable."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.space_after = Pt(1)
    r = p.add_run(text)
    style_run(r, size=size, color=color, name="DejaVu Sans")
    rPr = r._r.get_or_add_rPr()
    rtl = rPr.find(qn("w:rtl"))
    if rtl is not None:
        rPr.remove(rtl)
    return p


