def ltr_center_line(doc, text, size=9.5, color="808080"):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.space_after = Pt(1)
    r = p.add_run(text)
    style_run(r, size=size, color=color, name="DejaVu Sans")
    rPr = r._r.get_or_add_rPr()
    rtl = rPr.find(qn("w:rtl"))
    if rtl is not None:
        rPr.remove(rtl)
    return p


